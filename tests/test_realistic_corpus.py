"""Corpus integrity and full-source loading; imported sample code is never run."""
import ast
import hashlib
import json
from pathlib import Path
import tempfile
import unittest

from ai_lab.core import LAB, load_config, messages_for, snapshot
from ai_lab.suites import load_suite


class RealisticCorpusTests(unittest.TestCase):
    def setUp(self):
        self.config = load_config(LAB / "config.simple.json")

    def test_all_bundled_files_are_loaded_completely_with_a_reference(self):
        cases = load_suite("smoke", self.config)
        references = json.loads((LAB / "samples/manifest.json").read_text())
        names = {item["file"] for item in references}
        self.assertTrue(names.issubset({case["name"] for case in cases}))
        bundled = [case for case in cases if case["name"] in names]
        self.assertEqual(len(bundled), 27)
        self.assertTrue(all("input_error" not in case and case["rubric"] for case in bundled))
        self.assertEqual(sum(case["category"] == "algorithm_solution" for case in bundled), 18)
        self.assertEqual(sum(case["category"] == "ml_workflow" for case in bundled), 1)
        self.assertEqual(sum(case["category"] == "application_module" for case in bundled), 2)
        for case in bundled:
            self.assertEqual(case["source"], Path(case["source_path"]).read_text(encoding="utf-8-sig"))
            case["rubric"]["purpose"] = "PRIVATE_REFERENCE_SENTINEL"
            self.assertNotIn("PRIVATE_REFERENCE_SENTINEL", json.dumps(messages_for(case)))

    def test_a4_is_the_original_791_line_file_and_magic_syntax_does_not_discard_imports(self):
        path = LAB / "samples/real_world/a4.py"
        raw = path.read_bytes()
        self.assertEqual(hashlib.sha256(raw).hexdigest(), "3a635ee4ef26eed48c3a506886821587cb5d9952be19ed2e2dffe208dc9d3db2")
        case = snapshot(path, "real_world/a4.py", self.config["max_source_chars"])
        self.assertEqual(case["facts"]["line_count"], 791)
        self.assertEqual(len(case["source"]), 32663)
        self.assertEqual(case["source"], raw.decode("utf-8"))
        self.assertIn("!cp", case["source"])
        self.assertNotIn("parse_error", case["facts"])
        self.assertIn("transformers", case["facts"]["imports"])
        self.assertEqual(case["facts"]["shell_commands"][0]["line"], 12)
        self.assertIn("not a plain Python", case["facts"]["runtime_note"])

    def test_colab_export_shell_commands_are_not_executed_and_line_numbers_stay_stable(self):
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            marker = root / "must-not-exist"
            source = f'# Automatically generated by Colab.\n!touch "{marker}"\nimport csv\ndef work(value):\n    return value\n'
            path = root / "export.py"
            path.write_text(source)
            case = snapshot(path, path.name, 2500)
            self.assertFalse(marker.exists())
            self.assertEqual(case["source"], source)
            self.assertEqual(case["facts"]["imports"], ["csv"])
            self.assertEqual(case["facts"]["definitions"][0]["line"], 4)

    def test_external_sources_keep_exact_hashes_license_and_real_syntax_defects(self):
        base = LAB / "samples/leetcode"
        source = json.loads((base / "SOURCE.json").read_text())
        self.assertEqual(source["license"], "MIT")
        self.assertIn("Copyright (c) 2022 neetcode-gh", (base / "LICENSE").read_text())
        self.assertEqual(len(source["files"]), 18)
        for item in source["files"]:
            path = LAB / "samples" / item["file"]
            self.assertEqual(hashlib.sha256(path.read_bytes()).hexdigest(), item["sha256"])
            self.assertFalse(item["modified"])
        # The upstream file really contains an indentation defect; preserve and report it.
        path = base / "python/0200-number-of-islands.py"
        with self.assertRaises(SyntaxError):
            ast.parse(path.read_text())
        case = snapshot(path, path.name, self.config["max_source_chars"])
        self.assertIn("parse_error_line", case["facts"])
        self.assertIn("indent", case["facts"]["parse_error_detail"].lower())


if __name__ == "__main__":
    unittest.main()
