# Define a learning rate schedule with warm-up and cosine decay
class WarmUpCosineDecay(tf.keras.optimizers.schedules.LearningRateSchedule):
    def __init__(self, initial_learning_rate, max_learning_rate, warmup_steps, decay_steps, alpha=1e-6):
        super().__init__()
        self.initial_learning_rate = initial_learning_rate
        self.max_learning_rate = max_learning_rate
        self.warmup_steps = tf.cast(warmup_steps, tf.float32)
        self.decay_steps = tf.cast(decay_steps - warmup_steps, tf.float32)
        self.alpha = alpha

    def __call__(self, step):
        step = tf.cast(step, tf.float32)
        # Compute learning rate during warm-up phase
        warmup_lr = self.initial_learning_rate + \
                    (self.max_learning_rate - self.initial_learning_rate) * (step / self.warmup_steps)
        # Compute learning rate during cosine decay phase
        decay_step = step - self.warmup_steps
        cosine_decay = 0.5 * (1 + tf.cos(np.pi * decay_step / self.decay_steps))
        decayed = (1 - self.alpha) * cosine_decay + self.alpha
        decay_lr = self.max_learning_rate * decayed
        # Select appropriate learning rate
        learning_rate = tf.where(step < self.warmup_steps, warmup_lr, decay_lr)
        return learning_rate

    def get_config(self):
        return {
            "initial_learning_rate": self.initial_learning_rate,
            "max_learning_rate": self.max_learning_rate,
            "warmup_steps": self.warmup_steps.numpy(),
            "decay_steps": self.decay_steps.numpy(),
            "alpha": self.alpha,
        }

# Instantiate the learning rate schedule
