# Define training step
@tf.function
def train_step(images, masks):
    with tf.GradientTape() as tape:
        # Convert input images to channels_first format
        images_transposed = tf.transpose(images, perm=[0, 3, 1, 2])  # (batch_size, channels, height, width)
        # Forward pass through the model
        outputs = segformer_model(images_transposed, training=True)
        logits = outputs.logits  # (batch_size, num_labels, height, width)
        # Convert logits back to channels_last format
        logits = tf.transpose(logits, perm=[0, 2, 3, 1])  # (batch_size, height, width, num_labels)
        # Resize logits to match mask size
        logits = tf.image.resize(logits, size=tf.shape(masks)[1:3], method='bilinear')
        # Compute the cross-entropy loss
        loss = loss_fn(masks, logits)
        # Compute Dice Loss
        masks_one_hot = tf.one_hot(masks, depth=NUM_CLASSES)
        dice = dice_loss(masks_one_hot, tf.nn.softmax(logits, axis=-1))
        # Compute Boundary Loss
        b_loss = dice_edge_loss(masks, logits)
        # Total loss is a sum of individual losses
        total_loss = loss + dice + b_loss

    # Compute gradients and apply to model weights
    gradients = tape.gradient(total_loss, segformer_model.trainable_variables)
    optimizer.apply_gradients(zip(gradients, segformer_model.trainable_variables))

    # Update training metrics
    train_loss.update_state(total_loss)
    train_accuracy.update_state(masks, logits)
    train_dice.update_state(1 - dice)  # Convert Dice Loss to Dice Score
    train_ce_loss.update_state(loss)
    train_dice_loss.update_state(dice)
    train_boundary_loss.update_state(b_loss)

