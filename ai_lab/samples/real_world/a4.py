# Define Dice Loss and Dice Score
def dice_loss(y_true, y_pred, epsilon=1e-6):
    numerator = 2 * tf.reduce_sum(y_true * y_pred, axis=[1, 2, 3]) + epsilon
    denominator = tf.reduce_sum(y_true + y_pred, axis=[1, 2, 3]) + epsilon
    loss = 1 - numerator / denominator
    return tf.reduce_mean(loss)

def dice_score(y_true, y_pred, epsilon=1e-6):
    numerator = 2 * tf.reduce_sum(y_true * y_pred, axis=[1, 2, 3]) + epsilon
    denominator = tf.reduce_sum(y_true + y_pred, axis=[1, 2, 3]) + epsilon
    dice = numerator / denominator
    return dice

def dice_edge_loss(y_true, y_pred, epsilon=1e-6):
    # Convert labels and predictions to single-channel format
    y_true = tf.cast(y_true, tf.int32)
    y_pred = tf.argmax(tf.nn.softmax(y_pred, axis=-1), axis=-1, output_type=tf.int32)

    # Define Laplacian kernel for edge detection
    laplacian_filter = tf.constant([[0, 1, 0],
                                     [1, -4, 1],
                                     [0, 1, 0]], dtype=tf.float32)
    laplacian_filter = tf.reshape(laplacian_filter, [3, 3, 1, 1])

    # Compute edges for true and predicted masks
    y_true = tf.expand_dims(y_true, axis=-1)
    y_pred = tf.expand_dims(y_pred, axis=-1)

    y_true_edges = tf.nn.conv2d(tf.cast(y_true, tf.float32), laplacian_filter, strides=[1, 1, 1, 1], padding='SAME')
    y_pred_edges = tf.nn.conv2d(tf.cast(y_pred, tf.float32), laplacian_filter, strides=[1, 1, 1, 1], padding='SAME')

    y_true_edges = tf.cast(tf.abs(y_true_edges) > 0, tf.float32)
    y_pred_edges = tf.cast(tf.abs(y_pred_edges) > 0, tf.float32)

    # Compute Dice Loss for edges
    intersection = tf.reduce_sum(y_true_edges * y_pred_edges, axis=[1, 2, 3])
    union = tf.reduce_sum(y_true_edges + y_pred_edges, axis=[1, 2, 3])
    loss = 1 - (2 * intersection + epsilon) / (union + epsilon)

    return tf.reduce_mean(loss)

