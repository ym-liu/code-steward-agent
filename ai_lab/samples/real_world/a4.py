# Data generator function to handle preprocessing and augmentation
def data_generator(image_list, mask_list, batch_size, augment=False):
    # Define the data augmentation pipeline using Albumentations
    transform = A.Compose([
        A.HorizontalFlip(p=0.5),  # Random horizontal flip
        A.VerticalFlip(p=0.5),  # Random vertical flip
        A.RandomRotate90(p=0.5),  # Random 90-degree rotation
        A.Rotate(limit=15, p=0.5, border_mode=cv2.BORDER_REFLECT),  # Small rotations
        A.ShiftScaleRotate(shift_limit=0.05, scale_limit=0.05, rotate_limit=10, p=0.5, border_mode=cv2.BORDER_REFLECT),
        A.GridDistortion(p=0.5),  # Apply grid distortion
        A.RandomBrightnessContrast(p=0.5),  # Adjust brightness and contrast
        A.RandomGamma(gamma_limit=(80, 120), p=0.5),  # Adjust gamma
        A.GaussianBlur(p=0.2),
        A.CoarseDropout(
            max_holes=8, max_height=16, max_width=16, min_holes=1, min_height=8, min_width=8, p=0.5
        ),
    ], additional_targets={'mask': 'mask'})  # Treat masks as additional targets

    # Function to preprocess a single image
    def preprocess_image(image_path):
        image = cv2.imread(image_path.decode())  # Load image
        if image is None:
            raise ValueError(f"Image not found: {image_path.decode()}")
        image = cv2.cvtColor(image, cv2.COLOR_BGR2RGB)  # Convert BGR to RGB
        image = cv2.resize(image, TARGET_SIZE, interpolation=cv2.INTER_AREA)  # Resize
        return image.astype(np.uint8)

    # Function to preprocess a single mask
    def preprocess_mask(mask_path):
        mask = cv2.imread(mask_path.decode(), cv2.IMREAD_GRAYSCALE)  # Load mask
        if mask is None:
            raise ValueError(f"Mask not found: {mask_path.decode()}")
        mask = cv2.resize(mask, TARGET_SIZE, interpolation=cv2.INTER_NEAREST)  # Resize
        mask = mask.astype(np.uint8)
        mask = mask - 1  # Adjust mask values to start from 0
        return mask

    # Function to load and preprocess image and mask
    def load_and_preprocess(image_path, mask_path):
        image = tf.numpy_function(preprocess_image, [image_path], tf.uint8)  # Preprocess image
        mask = tf.numpy_function(preprocess_mask, [mask_path], tf.uint8)  # Preprocess mask
        image.set_shape([TARGET_SIZE[0], TARGET_SIZE[1], 3])  # Set static shape for image
        mask.set_shape([TARGET_SIZE[0], TARGET_SIZE[1]])  # Set static shape for mask
        return image, mask

    # Function to apply augmentations
    def augment_data(image, mask):
        augmented = transform(image=image, mask=mask)
        image_aug = augmented['image']
        mask_aug = augmented['mask']
        return image_aug.astype(np.uint8), mask_aug.astype(np.uint8)

    # Function to preprocess and optionally augment data
    def preprocess_and_augment(image_path, mask_path):
        image, mask = load_and_preprocess(image_path, mask_path)
        if augment:  # Apply augmentations if specified
            [image, mask] = tf.numpy_function(augment_data, [image, mask], [tf.uint8, tf.uint8])
            image.set_shape([TARGET_SIZE[0], TARGET_SIZE[1], 3])
            mask.set_shape([TARGET_SIZE[0], TARGET_SIZE[1]])
        # Normalize image
        image = tf.cast(image, tf.float32) / 255.0

        # Normalize specifically for SegFormer
        mean = tf.constant([0.485, 0.456, 0.406], dtype=tf.float32)
        std = tf.constant([0.229, 0.224, 0.225], dtype=tf.float32)
        image = (image - mean) / std

        # Convert mask to class indices
        mask = tf.cast(mask, tf.int32)

        return image, mask

    # Create a TensorFlow dataset from image and mask lists
    dataset = tf.data.Dataset.from_tensor_slices((image_list, mask_list))
    dataset = dataset.map(preprocess_and_augment, num_parallel_calls=tf.data.AUTOTUNE)
    if augment:
        dataset = dataset.shuffle(1000)  # Shuffle dataset for augmentation
    dataset = dataset.batch(batch_size).prefetch(tf.data.AUTOTUNE)  # Prefetch to improve performance
    return dataset

