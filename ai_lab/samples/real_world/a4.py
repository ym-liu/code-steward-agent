# Define a function to preprocess images
def preprocess_image(image_path):
    """
    Preprocesses a single image for prediction.

    Args:
        image_path: Path to the image.

    Returns:
        Preprocessed image normalized for the model, and its original size.
    """
    image_file = tf.io.read_file(image_path)

    # Decode the image based on file extension
    def decode_image():
        file_extension = tf.strings.lower(tf.strings.regex_replace(image_path, r'^.*\.', ''))
        def decode_jpeg():
            return tf.image.decode_jpeg(image_file, channels=3)
        def decode_png():
            return tf.image.decode_png(image_file, channels=3)
        return tf.case([
            (tf.logical_or(tf.equal(file_extension, 'jpg'), tf.equal(file_extension, 'jpeg')), decode_jpeg),
            (tf.equal(file_extension, 'png'), decode_png),
        ], exclusive=True, default=lambda: tf.zeros([0, 0, 3], dtype=tf.uint8))

    image = decode_image()

    # Check if decoding was successful
    image_shape = tf.shape(image)
    is_valid = tf.reduce_all(image_shape > 0)

    # If decoding is successful, preprocess the image
    def valid_image():
        image.set_shape([None, None, 3])
        original_size = tf.shape(image)[:2]
        resized_image = tf.image.resize(image, TARGET_SIZE, method=tf.image.ResizeMethod.AREA)
        resized_image = tf.cast(resized_image, tf.float32) / 255.0  # Normalize pixel values to [0, 1]

        # Normalize image for SegFormer
        mean = tf.constant([0.485, 0.456, 0.406], dtype=tf.float32)
        std = tf.constant([0.229, 0.224, 0.225], dtype=tf.float32)
        normalized_image = (resized_image - mean) / std

        return normalized_image, original_size

    # If decoding fails, log the error and return a placeholder image
    def invalid_image():
        tf.print("Failed to decode image:", image_path)
        placeholder_image = tf.zeros([TARGET_SIZE[0], TARGET_SIZE[1], 3], dtype=tf.float32)
        return placeholder_image, tf.constant([TARGET_SIZE[0], TARGET_SIZE[1]], dtype=tf.int32)

    image, original_size = tf.cond(is_valid, valid_image, invalid_image)

    return image, original_size

