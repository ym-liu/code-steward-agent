# Helper function for K-Means segmentation
def kmeans_segmentation(image, k=3):
    h, w, c = image.shape
    image_flat = image.reshape((-1, c))  # Flatten the image
    kmeans = KMeans(n_clusters=k, random_state=SEED).fit(image_flat)
    segmented_flat = kmeans.labels_
    segmented_image = segmented_flat.reshape((h, w))
    return segmented_image

# Function to compute Dice Coefficient Score
def dice_coefficient_score(y_true, y_pred, num_classes=NUM_CLASSES):
    dice_scores = []
    y_true = np.argmax(y_true, axis=-1)  # Convert one-hot to single channel
    for i in range(num_classes):
        y_true_class = (y_true == i).astype(np.float32)
        y_pred_class = (y_pred == i).astype(np.float32)
        intersection = np.sum(y_true_class * y_pred_class)
        union = np.sum(y_true_class) + np.sum(y_pred_class)
        dice = (2 * intersection) / (union + 1e-6)
        dice_scores.append(dice)
    return dice_scores

# Evaluate K-Means on validation set
def evaluate_kmeans_on_validation(val_images, val_masks, k=3):
    dice_scores_all = []
    for img_path, mask_path in zip(val_images, val_masks):
        # Load and preprocess
        image, mask = load_and_preprocess(img_path, mask_path)

        # Perform K-Means segmentation
        segmented_image = kmeans_segmentation(image, k=k)

        # Calculate Dice Coefficient Score
        dice_scores = dice_coefficient_score(mask, segmented_image)
        dice_scores_all.append(dice_scores)

    # Average Dice scores across all images
    avg_dice_scores_per_class = np.mean(dice_scores_all, axis=0)  # Per-class average
    overall_dice_score = np.mean(avg_dice_scores_per_class)  # Overall average
    return overall_dice_score

