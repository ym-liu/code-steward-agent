def passed_by_script(line):
    """For a line that forwards the script's arguments: (program, options the script adds itself)."""
    tokens = [token.strip("\"'") for token in line.split()]
    while tokens and tokens[0].lower() in LAUNCH_WORDS:
        tokens.pop(0)
    if not tokens:
        return None, []
    fixed = [token for token in tokens[1:] if token and not ALL_ARGUMENTS.search(token) and not NUMBERED_ARGUMENT.search(token)]
    return tokens[0], fixed


def signature_from(line, suffix, owner):
    if suffix in (".java", ".cs", ".kt"):
        match = JAVA_METHOD.match(line)
        if not match or match.group(2) in NOT_FUNCTIONS:
            return None
        kind, name, parameters = match.groups()
        result = kind if kind and kind != "void" and name != owner else None
    else:
        match = CPP_METHOD.match(line)
        if not match or match.group(2) in NOT_FUNCTIONS:
            return None
        kind, name, parameters = match.groups()
        result = re.sub(r"\s+", "", kind) if kind.strip() != "void" else None
    text = f"{name}({' '.join(parameters.split())})" + (f" -> {result}" if result else "")
    return name, text[:120]


def c_family_interface(code, suffix):
    """Classes with public methods, and top-level functions, from brace depth and access labels (approximate)."""
    classes, functions, stack, depth = {}, [], [], 0
    for number, line in code:
        stripped = line.strip()
        label = re.match(r"(public|private|protected)\s*:", stripped)
        found = DEFINED_TYPE.search(line)
        if label and stack:
            stack[-1][2] = label.group(1)
        elif found and not stripped.endswith(";"):
            kind, name = found.groups()
            public = kind in ("struct", "interface") or suffix in (".java", ".cs", ".kt")
            stack.append([name, depth + 1, "public" if public else "private"])
            classes.setdefault(name, {"name": name, "line": number, "kind": kind, "methods": []})
        elif stack and depth == stack[-1][1]:
            needs_keyword = suffix in (".java", ".cs", ".kt")
            signature = signature_from(line, suffix, stack[-1][0])
            if signature and (stripped.startswith("public") if needs_keyword else stack[-1][2] == "public"):
                classes[stack[-1][0]]["methods"].append(signature[1])
        elif not stack and depth == 0:
            signature = signature_from(line, suffix, None)
            if signature:
                functions.append({"name": signature[0], "line": number, "kind": "function", "signature": signature[1]})
        closes = line.count("}")
        depth += line.count("{") - closes
        while closes and stack and depth < stack[-1][1]:
            stack.pop()
    definitions = []
    for item in classes.values():
        if not item["methods"]:
            del item["methods"]
        else:
            item["methods"] = item["methods"][:FACT_LIMIT]
        definitions.append(item)
    return (definitions + functions)[:20]


def missing_standard_names(code, suffix, imports, defined):
    """Standard containers/streams used without the #include or import that provides them."""
    missing = []
    if suffix in (".c", ".h", ".cc", ".cpp", ".cxx", ".hpp") and "bits/stdc++.h" not in imports:
        for name, header in CPP_HEADERS.items():
            pattern = rf"\b(?:std::)?{name}\s*<" if header not in ("string", "sstream", "iostream") else rf"\b(?:std::)?{name}\b"
            number = next((n for n, line in code if re.search(pattern, line)), None)
            if number and header not in imports:
                missing.append({"name": name, "line": number, "note": f"no #include <{header}>"})
    elif suffix == ".java" and "java.util.*" not in imports:
        for name in sorted(JAVA_UTIL - defined):
            number = next((n for n, line in code if re.search(rf"\b{name}\b", line)), None)
            if number and f"java.util.{name}" not in imports:
                missing.append({"name": name, "line": number, "note": f"no import java.util.{name}"})
    return missing


def comment_lines(source, suffix):
    """Line numbers that hold only comments, including C-style /* ... */ blocks."""
    lines, found = source.splitlines(), set()
    if suffix == ".py" or suffix in COMMENT_MARKERS:
        markers = ("#",) if suffix == ".py" else COMMENT_MARKERS[suffix]
        return {n for n, line in enumerate(lines, 1) if line.strip().lower().startswith(markers)
                and not line.strip().startswith("#!")}
    in_block = False
    for number, line in enumerate(lines, 1):
        stripped = line.strip()
        if in_block:
            found.add(number)
            in_block = "*/" not in stripped
        elif stripped.startswith(("//", "*")):
            found.add(number)
        elif stripped.startswith("/*"):
            found.add(number)
            in_block = "*/" not in stripped[2:]
        elif "/*" in stripped:
            in_block = "*/" not in stripped[stripped.index("/*") + 2:]
    return found


def other_facts(source, suffix):
    """Approximate regex facts for non-Python code; comment lines are skipped."""
    lines, facts = source.splitlines(), {}
    skipped = comment_lines(source, suffix)
    code, comments = [], []
    for number, line in enumerate(lines, 1):
        if line.strip():
            (comments if number in skipped or line.startswith("#!") else code).append((number, line))
    for suffixes, import_rule, entry_rule, entry_kind in OTHER_LANGUAGE_RULES.values():
        if suffix in suffixes:
            facts["imports"] = sorted({group for _, line in code for match in re.finditer(import_rule, line)
                                       for group in match.groups() if group})
            if entry_rule:
                number = next((n for n, line in code if re.search(entry_rule, line)), None)
                facts["entry_point"] = {"kind": entry_kind, "line": number} if number else None
            definitions = c_family_interface(code, suffix) if suffix not in (".js", ".jsx", ".ts", ".tsx", ".go", ".rs") else \
                [{"name": name, "line": n, "kind": kind} for n, line in code for kind, name in DEFINED_TYPE.findall(line)][:20]
            if definitions:
                facts["definitions"] = definitions
            defined = {item["name"] for item in definitions}
            missing = missing_standard_names(code, suffix, set(facts["imports"]), defined)
            # LeetCode-style excerpts show ListNode/TreeNode only inside a comment.
            commented = {name for _, line in comments for _, name in DEFINED_TYPE.findall(line) if name[0].isupper()}
            for name in sorted(commented - defined):
                number = next((n for n, line in code if re.search(rf"\b{name}\b", line)), None)
                if number:
                    missing.append({"name": name, "line": number, "note": "defined only in a comment"})
            if missing:
                facts["names_without_visible_definition"] = sorted(missing, key=lambda item: item["line"])[:FACT_LIMIT]
    if suffix in SCRIPT_EXTENSIONS:
        first = next((n for n, line in code if not line.strip().lower().startswith("@echo")), None)
        facts["entry_point"] = {"kind": "script", "line": first} if first else None
        arguments = []
        for number, line in code:
            if SCRIPT_ARGUMENTS.search(line):
                uses = ["all arguments given to this script"] if ALL_ARGUMENTS.search(line) else []
                uses += [f"argument {a or b}" for a, b in NUMBERED_ARGUMENT.findall(line)]
                item = {"line": number, "code": line.strip()[:100], "uses": ", ".join(dict.fromkeys(uses)) or "declared parameters"}
                program, fixed = passed_by_script(line) if ALL_ARGUMENTS.search(line) else (None, [])
                if program and fixed:
                    item["note"] = (f"The script itself passes {' '.join(fixed)} to {program}; "
                                    "the user's own arguments are added after that.")
                arguments.append(item)
        if arguments:
            facts["command_line"] = arguments[:FACT_LIMIT]
    references = {}
    for number, line in code:
        for match in STRING_LITERAL.finditer(line):
            text = (match.group(1) or match.group(2)).strip()
            if PATH_LIKE.match(text):
                references.setdefault(text, number)
        if suffix in SCRIPT_EXTENSIONS:
            for match in BARE_PATH.finditer(line):
                references.setdefault(match.group(1), number)
    if references:
        facts["file_references"] = file_references(references)
    return facts


def run_summary(entry, estimated=False):
    """Plain-language answer to "does anything run when this file is executed?"."""
    note = " (estimated: the file has a syntax error)" if estimated else ""
    if entry is None:
        return f"No{note}. Nothing runs when this file is executed by itself; other code must use its classes or functions."
    if entry["kind"] == "main guard":
        return f"Yes{note}, through the if __name__ == \"__main__\" block at line {entry['line']}."
    if entry["kind"] == "top-level code":
        return f"Yes{note}. Top-level statements run from line {entry['line']}."
    if entry["kind"] == "script":
        return "Yes. The script runs from top to bottom when started."
    return f"Yes, through the {entry['kind']} at line {entry['line']}."


FACT_ORDER = ["language", "extension", "line_count", "runs_when_executed", "entry_point", "imports", "main_imports",
              "unused_imports", "definitions", "definitions_total", "argument_declarations",
              "argument_declarations_total", "command_line", "asks_user_for_input", "reads_files", "writes_files",
              "runs_commands", "file_references", "names_without_visible_definition", "source_dialect",
              "shell_commands", "runtime_note", "parse_error", "parse_error_line", "parse_error_detail"]


def static_facts(source, suffix):
    facts = {"language": LANGUAGES.get(suffix, "unknown"), "extension": suffix,
             "line_count": len(source.splitlines()), "imports": []}
    if suffix == ".py":
        tree, extra = parse_python(source)
        if tree is not None:
            try:
                facts.update(python_facts(tree, source, "source_dialect" in extra))
            except RecursionError:
                extra = {"parse_error": "Python syntax is too deeply nested to analyze; imports are incomplete."}
        facts.update(extra)
        if "parse_error" in facts:
            facts["entry_point"] = estimated_python_entry(source)
            definitions = python_definitions_by_lines(source)
            if definitions:
                facts["definitions"] = definitions
    elif suffix != ".txt":
        facts.update(other_facts(source, suffix))
    if "entry_point" in facts:
        entry = facts["entry_point"]
        facts["runs_when_executed"] = run_summary(entry, "parse_error" in facts)
        if entry and entry.pop("estimated", False):
            entry["kind"] += " (estimated)"
    return {key: facts[key] for key in FACT_ORDER if key in facts} | \
        {key: value for key, value in facts.items() if key not in FACT_ORDER}
